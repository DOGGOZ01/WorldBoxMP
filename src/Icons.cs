        static readonly Dictionary<string, Sprite> _made = new Dictionary<string, Sprite>();

        public static Sprite Get(string name)
        {
            if (_made.TryGetValue(name, out Sprite s) && s != null) return s;
            string[] rows = Art[name];
            int size = rows.Length;
            var tex = new Texture2D(size, size, TextureFormat.RGBA32, false) { filterMode = FilterMode.Point, wrapMode = TextureWrapMode.Clamp, name = "wbmp_" + name };
            var px = new Color32[size * size];
            for (int y = 0; y < size; y++)
                for (int x = 0; x < size; x++)
                {
                    char c = rows[size - 1 - y][x];
                    px[y * size + x] = Palette.TryGetValue(c, out Color32 col) ? col : new Color32(0, 0, 0, 0);
                }
            tex.SetPixels32(px);
            tex.Apply(false, true);
            s = Sprite.Create(tex, new Rect(0, 0, size, size), new Vector2(0.5f, 0.5f), 16f);
            s.name = "wbmp_" + name;
            _made[name] = s;
            return s;
        }
